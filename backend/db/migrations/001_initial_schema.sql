CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'student' CONSTRAINT users_role_check CHECK (role IN ('student', 'lecturer', 'admin')),
  avatar_url VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS courses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  category VARCHAR(100) NOT NULL DEFAULT 'General',
  thumbnail_url VARCHAR(500),
  lecturer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  price NUMERIC(10,2) NOT NULL DEFAULT 0 CONSTRAINT courses_price_check CHECK (price >= 0),
  level VARCHAR(50) NOT NULL DEFAULT 'Beginner',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chapters (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  title VARCHAR(255) NOT NULL,
  chapter_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id, course_id)
);

CREATE TABLE IF NOT EXISTS lessons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  chapter_id INTEGER REFERENCES chapters(id) ON DELETE SET NULL,
  title VARCHAR(255) NOT NULL,
  content TEXT,
  video_url VARCHAR(500),
  file_url VARCHAR(500),
  file_name VARCHAR(255),
  file_type VARCHAR(50),
  lesson_order INTEGER NOT NULL DEFAULT 0,
  duration VARCHAR(50),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT lessons_chapter_course_fk FOREIGN KEY (chapter_id, course_id)
    REFERENCES chapters(id, course_id)
);

CREATE TABLE IF NOT EXISTS enrollments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  enrolled_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, course_id)
);

CREATE TABLE IF NOT EXISTS lesson_progress (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id INTEGER NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  completed_at TIMESTAMPTZ,
  UNIQUE (student_id, lesson_id)
);

CREATE TABLE IF NOT EXISTS notes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id INTEGER NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, lesson_id)
);

CREATE TABLE IF NOT EXISTS comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id INTEGER NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  parent_id INTEGER REFERENCES comments(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS forum_topics (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INTEGER REFERENCES courses(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(255) NOT NULL,
  content TEXT NOT NULL,
  views INTEGER NOT NULL DEFAULT 0 CONSTRAINT forum_topics_views_check CHECK (views >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS forum_replies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id INTEGER NOT NULL REFERENCES forum_topics(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS assignments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  chapter_id INTEGER REFERENCES chapters(id) ON DELETE SET NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  type VARCHAR(10) NOT NULL DEFAULT 'quiz' CONSTRAINT assignments_type_check CHECK (type IN ('quiz', 'essay')),
  total_points INTEGER NOT NULL DEFAULT 100 CONSTRAINT assignments_total_points_check CHECK (total_points > 0),
  due_date TIMESTAMPTZ,
  status VARCHAR(20) NOT NULL DEFAULT 'published' CONSTRAINT assignments_status_check CHECK (status IN ('draft', 'published', 'archived')),
  shuffle_questions BOOLEAN NOT NULL DEFAULT FALSE,
  shuffle_options BOOLEAN NOT NULL DEFAULT FALSE,
  time_limit INTEGER CONSTRAINT assignments_time_limit_check CHECK (time_limit IS NULL OR time_limit > 0),
  max_attempts INTEGER NOT NULL DEFAULT 1 CONSTRAINT assignments_max_attempts_check CHECK (max_attempts >= 0),
  allow_resubmit BOOLEAN NOT NULL DEFAULT FALSE,
  attachment_url VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT assignments_chapter_course_fk FOREIGN KEY (chapter_id, course_id)
    REFERENCES chapters(id, course_id)
);

CREATE TABLE IF NOT EXISTS assignment_questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id INTEGER NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  question_text TEXT NOT NULL,
  options JSONB NOT NULL DEFAULT '[]'::jsonb,
  correct_option INTEGER NOT NULL DEFAULT 0,
  points INTEGER NOT NULL DEFAULT 10 CONSTRAINT assignment_questions_points_check CHECK (points > 0),
  question_type VARCHAR(20) NOT NULL DEFAULT 'multiple_choice'
    CONSTRAINT assignment_questions_type_check CHECK (question_type IN ('multiple_choice', 'true_false', 'fill_blank', 'essay')),
  correct_answer TEXT,
  question_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS assignment_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id INTEGER NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content TEXT,
  answers JSONB,
  score INTEGER CONSTRAINT assignment_submissions_score_check CHECK (score IS NULL OR score >= 0),
  feedback TEXT,
  file_url VARCHAR(500),
  status VARCHAR(20) NOT NULL DEFAULT 'submitted'
    CONSTRAINT assignment_submissions_status_check CHECK (status IN ('submitted', 'graded')),
  attempt_number INTEGER NOT NULL DEFAULT 1 CONSTRAINT assignment_submissions_attempt_check CHECK (attempt_number > 0),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (assignment_id, student_id, attempt_number)
);

CREATE TABLE IF NOT EXISTS events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  lecturer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(255) NOT NULL,
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  event_type VARCHAR(20) NOT NULL DEFAULT 'lecture'
    CONSTRAINT events_type_check CHECK (event_type IN ('lecture', 'deadline', 'livestream', 'other')),
  meeting_link VARCHAR(500),
  status VARCHAR(20) NOT NULL DEFAULT 'upcoming'
    CONSTRAINT events_status_check CHECK (status IN ('upcoming', 'completed', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT events_time_order_check CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type VARCHAR(50) NOT NULL
    CONSTRAINT notifications_type_check CHECK (type IN ('assignment_posted', 'quiz_posted', 'submission_received', 'grade_posted')),
  title VARCHAR(255) NOT NULL,
  message TEXT,
  reference_id INTEGER,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
